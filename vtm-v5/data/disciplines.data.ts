export const getDisciplineByName = (name: string) =>
  DISCIPLINES.find(d => d.name === name || d.nameRu === name)

export const getDisciplinePowersByLevel = (disciplineName: string, level: number) =>
  getDisciplineByName(disciplineName)?.powers.filter(p => p.level === level) ?? []
